# fs_scaffold DIR VERSION VERDANDI_URL VERDANDI_REV: a minimal but real eitri-shaped checkout --
# just enough for checkout_version, lockfile_rev and agent_toml_verdandi to read something real, and
# for from_source_stage to find real files at the paths it copies (the launcher, the desktop entry,
# this installer itself, LICENSE). Not committed yet -- the caller commits and tags.
fs_scaffold() {
	_fs_dir=$1
	rm -rf "$_fs_dir"
	mkdir -p "$_fs_dir/shell" "$_fs_dir/agent" "$_fs_dir/packaging"
	# The real tree's own shape (Task 1, D1): shell/Cargo.toml names `version.workspace = true`, not
	# a plain quoted string, and the version itself lives once in the root's [workspace.package]
	# (installer-codex-2: checkout_version used to die against exactly this shape).
	{
		printf '[workspace]\n'
		printf 'resolver = "2"\n'
		printf 'members = ["shell", "agent"]\n'
		printf '\n[workspace.package]\n'
		printf 'version = "%s"\n' "$2"
		printf 'edition = "2021"\n'
	} >"$_fs_dir/Cargo.toml"
	{
		printf '[package]\n'
		printf 'name = "shell"\n'
		printf 'version.workspace = true\n'
		printf 'edition.workspace = true\n'
	} >"$_fs_dir/shell/Cargo.toml"
	{
		printf '[package]\n'
		printf 'name = "agent"\n'
		printf 'version = "%s"\n' "$2"
		printf 'edition.workspace = true\n'
		printf '\n[dependencies]\n'
		printf 'claude-runtime-protocol = { git = "%s", rev = "%s" }\n' "$3" "$4"
	} >"$_fs_dir/agent/Cargo.toml"
	{
		printf '# This file is automatically @generated by Cargo.\nversion = 3\n\n'
		printf '[[package]]\n'
		printf 'name = "neovide"\n'
		printf 'version = "0.1.0"\n'
		printf 'source = "git+https://example.invalid/neovide.git?rev=%s#%s"\n' "$FS_FORK_REV" "$FS_FORK_REV"
	} >"$_fs_dir/Cargo.lock"
	{
		printf 'NODE_VERSION=%s\n' "$NODE_FIXTURE_VERSION"
		printf 'NODE_SHA256_linux_x64=%s\n' "$NODE_FIXTURE_SHA256_X64"
		printf 'NODE_SHA256_linux_arm64=%s\n' "$NODE_FIXTURE_SHA256_ARM64"
		printf 'NVIM_VERSION=%s\n' "$NVIM_FIXTURE_VERSION"
		printf 'NVIM_SHA256_linux_x86_64=%s\n' "$NVIM_FIXTURE_SHA256"
		printf 'SKIA_BINARIES_URL_UPSTREAM=%s\n' "$SKIA_FIXTURE_URL"
		printf 'SKIA_BINARIES_SHA256=%s\n' "$SKIA_FIXTURE_SHA256"
	} >"$_fs_dir/packaging/pins.env"
	cp "$PKG/eitri.launcher.sh" "$_fs_dir/packaging/eitri.launcher.sh"
	cp "$PKG/cn.huntergrey.eitri.desktop" "$_fs_dir/packaging/cn.huntergrey.eitri.desktop"
	cp "$PKG/cn.huntergrey.eitri.Panel.desktop" "$_fs_dir/packaging/cn.huntergrey.eitri.Panel.desktop"
	mkdir -p "$_fs_dir/nvim"
	cp -R "$PKG/../nvim/eitri.nvim" "$_fs_dir/nvim/eitri.nvim"
	cp -R "$PKG/../gnome-extension" "$_fs_dir/gnome-extension"
	cp -R "$PKG/icons" "$_fs_dir/packaging/icons"
	cp "$INSTALLER" "$_fs_dir/packaging/install.sh"
	printf 'test fixture LICENSE: MIT-shaped, not the real text.\n' >"$_fs_dir/LICENSE"
}

# fs_commit_and_tag DIR VERSION: sets FS_HEAD to the real commit sha.
fs_commit_and_tag() {
	# shellcheck disable=SC2086 # FS_GIT_ID is deliberately several words
	git -C "$1" init -q
	# shellcheck disable=SC2086
	git -C "$1" $FS_GIT_ID add -A
	# shellcheck disable=SC2086
	git -C "$1" $FS_GIT_ID commit -q -m base
	git -C "$1" tag "v$2"
	FS_HEAD=$(git -C "$1" rev-parse HEAD)
}

# fs_repo VERSION VERDANDI_URL VERDANDI_REV: fs_scaffold + fs_commit_and_tag under $T, once per
# call. Sets FS_DIR and FS_HEAD.
fs_repo() {
	FS_DIR=$T/fs-repo
	fs_scaffold "$FS_DIR" "$1" "$2" "$3"
	fs_commit_and_tag "$FS_DIR" "$1"
}

# fs_verdandi_checkout DIR: a minimal but real Verdandi checkout (like mk_verdandi_source, but a
# real git working tree, for --verdandi-checkout's own rev/status checks). Sets FS_VC_HEAD.
fs_verdandi_checkout() {
	_fvc=$1
	rm -rf "$_fvc"
	mkdir -p "$_fvc/apps/claude-sidecar/scripts"
	printf '{\n  "name": "verdandi",\n  "private": true\n}\n' >"$_fvc/package.json"
	printf '{\n  "name": "@verdandi/claude-sidecar",\n  "version": "0.1.0"\n}\n' >"$_fvc/apps/claude-sidecar/package.json"
	printf '// test fixture: never run\n' >"$_fvc/apps/claude-sidecar/scripts/buildBinary.mjs"
	# shellcheck disable=SC2086
	git -C "$_fvc" init -q
	# shellcheck disable=SC2086
	git -C "$_fvc" $FS_GIT_ID add -A
	# shellcheck disable=SC2086
	git -C "$_fvc" $FS_GIT_ID commit -q -m base
	FS_VC_HEAD=$(git -C "$_fvc" rev-parse HEAD)
}

# mk_from_source_release VERSION REV COMMIT: mk_release (the shared harness fixture builder), with
# its own always-fake EITRI_COMMIT replaced by COMMIT (a from-source fixture repo's real HEAD) and
# re-signed. A fresh VERSION every caller uses (9.9.x), never one of setup_releases' own 1.x.y
# versions: mutating those in place would corrupt every other test file's shared fixtures.
mk_from_source_release() {
	mk_release "$1" "$2"
	sed -i "s/^EITRI_COMMIT=.*/EITRI_COMMIT=$3/" "$S/fix/v$1/RELEASE"
	resign "$S/fix/v$1"
}

# fs_cargo_stubs: PRE_STUBS-ready directory holding the recording cargo stub (fixtures/cargo-fromsource,
# shared: harness.sh's own setup_stubs built it once, under $S itself, as $S/stubs-cargo -- its own
# `S=$(cd "$(dirname "$0")/.." && pwd)` only resolves to the real $S from a directory one level under
# it) under the name `cargo`, and nothing else -- $S/stubs (right after it) still supplies the
# forbidden commands and claude, and /usr/bin:/bin (the default path-tail, right after that) supplies
# the real rustc/cc/pkg-config/protoc/git check_build_tools also needs, none of which any test here
# stubs.
fs_cargo_stubs() { printf '%s\n' "$S/stubs-cargo"; }

