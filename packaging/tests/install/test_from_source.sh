# F2 (v1-dist whole-branch review, 2026-09-28): semver_cmp's downgrade refusal used to be called
# only from do_install -- --from-source never refused a downgrade at all, so a mirror serving an
# older, genuinely signed release rolled a from-source user silently backward, which is exactly the
# rollback case spec §6.4 says a signature does not cover.
TESTS="$TESTS t_from_source_older_version_refused"
t_from_source_older_version_refused() {
	FS_FORK_REV=eeeeeee111111111111111111111111111111111
	fs_repo 9.9.10 https://github.com/HunterGrey-cyber/verdandi.git ddddddd000000000000000000000000000000000
	mk_from_source_release 9.9.10 ddddddd000000000000000000000000000000000 "$FS_HEAD"
	serve 9.9.10
	# The installed version comes from a plain prebuilt install -- a from-source build's own output
	# is installed the same way as a tarball's (finish_install), so this is a faithful "already
	# installed" starting point.
	inst_net --version 9.9.10
	expect_rc 0
	expect_eq "$(installed_version)" 9.9.10

	fs_repo 9.9.9 https://github.com/HunterGrey-cyber/verdandi.git ddddddd000000000000000000000000000000000
	mk_from_source_release 9.9.9 ddddddd000000000000000000000000000000000 "$FS_HEAD"
	serve 9.9.9 9.9.10
	before=$(snap "$TH")
	PRE_STUBS=$(fs_cargo_stubs)
	inst --set "EITRI_INSTALL_TEST_REPO_URL=$FS_DIR" \
		--set "EITRI_INSTALL_TEST_NODE_BASE_URL=http://127.0.0.1:$PORT/dist" \
		-- --from-source --base-url "http://127.0.0.1:$PORT" --release-signers "$SIGNERS"
	expect_fail "a from-source downgrade without --version"
	expect_out 'Eitri 9.9.10 is installed, and the release offered is older (9.9.9): refusing to downgrade silently'
	expect_out '--version 9.9.9'
	expect_eq "$(snap "$TH")" "$before" "the home after a refused from-source downgrade"
	if [ -f "$S/logs/cargo.log" ] && grep -q '^cargo build ' "$S/logs/cargo.log"; then
		fail "cargo build ran despite the downgrade refusal: $(cat "$S/logs/cargo.log")"
	fi

	# With --version, the refusal does not apply: the run proceeds to a real clone-and-build.
	inst --set "EITRI_INSTALL_TEST_REPO_URL=$FS_DIR" \
		--set "EITRI_INSTALL_TEST_NODE_BASE_URL=http://127.0.0.1:$PORT/dist" \
		--set "EITRI_INSTALL_TEST_SKIA_BASE_URL=http://127.0.0.1:$PORT/skia" \
		-- --from-source --version 9.9.9 --base-url "http://127.0.0.1:$PORT" --release-signers "$SIGNERS"
	expect_rc 0
	expect_eq "$(installed_version)" 9.9.9 "the explicit from-source downgrade"
}

