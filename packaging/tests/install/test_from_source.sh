# fs_repo_public VERSION VERDANDI_URL VERDANDI_REV: fs_repo in the PUBLIC tree's shape (publish/export.sh):
# Cargo.lock names no git source for neovide, and neovide/ is a git submodule (a gitlink HEAD records)
# checked out from a small fixture repo. Sets FS_DIR, FS_HEAD and FS_NEOVIDE_HEAD (v1-dist Task 12
# sub-plan Task 5: --from-source --checkout used to die in a public clone for want of that source line).
fs_repo_public() {
	FS_NEOVIDE_SRC=$T/neovide-src
	rm -rf "$FS_NEOVIDE_SRC"
	mkdir -p "$FS_NEOVIDE_SRC"
	printf 'fixture fork\n' >"$FS_NEOVIDE_SRC/README"
	git -C "$FS_NEOVIDE_SRC" init -q
	# shellcheck disable=SC2086
	git -C "$FS_NEOVIDE_SRC" $FS_GIT_ID add -A
	# shellcheck disable=SC2086
	git -C "$FS_NEOVIDE_SRC" $FS_GIT_ID commit -q -m fork-one
	FS_NEOVIDE_HEAD=$(git -C "$FS_NEOVIDE_SRC" rev-parse HEAD)
	FS_DIR=$T/fs-repo
	# fs_scaffold writes a private-shape Cargo.lock from FS_FORK_REV; it is replaced right below.
	FS_FORK_REV=eeeeeee111111111111111111111111111111111
	fs_scaffold "$FS_DIR" "$1" "$2" "$3"
	{
		printf '# This file is automatically @generated by Cargo.\nversion = 3\n\n'
		printf '[[package]]\n'
		printf 'name = "neovide"\n'
		printf 'version = "0.1.0"\n'
	} >"$FS_DIR/Cargo.lock"
	git -C "$FS_DIR" init -q
	# shellcheck disable=SC2086
	git -C "$FS_DIR" $FS_GIT_ID -c protocol.file.allow=always submodule add -q "$FS_NEOVIDE_SRC" neovide
	# shellcheck disable=SC2086
	git -C "$FS_DIR" $FS_GIT_ID add -A
	# shellcheck disable=SC2086
	git -C "$FS_DIR" $FS_GIT_ID commit -q -m base
	git -C "$FS_DIR" tag "v$1"
	FS_HEAD=$(git -C "$FS_DIR" rev-parse HEAD)
}

